(function () {

  /* ─────────────── 고치는 곳 · 여기만 만지면 된다 ─────────────── */

  var B = {

    /* 1층 · 간판 — 처음 만나는 손님에게 (공유문·미리보기·상세페이지) */
    sign: '가장 소중한 사람을 더 알아가는 시간, 사랑흐름',

    /* 2층 · 철학 — 들어온 손님에게 (about) */
    philosophy: '우리의 관계는 이미 시작되었습니다',

    /* 3층 · 제품 — 사려는 손님에게 (상품 설명) */
    product: '서로의 언어를 읽어갑니다',

    /* about 신조 문단 — 강조(<em>)가 들어간 두 줄짜리 */
    creed: '우리의 관계는 <em>이미 시작되었습니다</em>.<br>' +
           '사랑흐름은 <em>서로의 언어</em>를 읽어갑니다.',

    /* 카톡·문자로 나가는 공유 한 줄 */
    share: '가장 소중한 사람을 더 알아가는 시간, 사랑흐름',

    /* 메뉴 항목 이름 */
    menuJourney: '함께 떠나기'

  };

  /* ─────────────── 아래는 만지지 않는다 ─────────────── */

  window.LF_BRAND = B;

  function apply() {
    var nodes = document.querySelectorAll('[data-lf]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-lf');
      var val = B[key];
      if (typeof val === 'string' && val !== '') {
        nodes[i].innerHTML = val;
      }
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', apply);
  } else {
    apply();
  }

})();
